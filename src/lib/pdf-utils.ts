import { jsPDF } from 'jspdf';
import logoUrl from '@/assets/metastudy-icon.png';

interface PDFOptions {
  filename: string;
  margin?: number;
  pageSize?: 'letter' | 'a4';
}

/**
 * Load an image URL and return base64 data for jsPDF
 */
function loadImageBase64(url: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      if (!ctx) { reject(new Error('Canvas context failed')); return; }
      ctx.drawImage(img, 0, 0);
      resolve(canvas.toDataURL('image/png'));
    };
    img.onerror = () => reject(new Error('Failed to load logo'));
    img.src = url;
  });
}

/**
 * Sanitize text so every character is in the WinAnsiEncoding range that
 * jsPDF's built-in helvetica font can actually render. Characters outside
 * that range are replaced with safe ASCII equivalents.
 */
function sanitizeForPDF(text: string): string {
  return text
    // Common Unicode bullets / dashes
    .replace(/[\u2022\u2023\u25E6\u2043\u2219]/g, '-')
    .replace(/[\u2013\u2014\u2015]/g, '-')
    .replace(/[\u2018\u2019\u201A]/g, "'")
    .replace(/[\u201C\u201D\u201E]/g, '"')
    .replace(/\u2026/g, '...')
    .replace(/[\u00A0]/g, ' ')
    // Box-drawing / decorative lines
    .replace(/[\u2500-\u257F]/g, '-')
    .replace(/[\u2550-\u256C]/g, '=')
    // Any remaining non-Latin1 characters → space
    .replace(/[^\x00-\xFF]/g, ' ');
}

/**
 * Add header with metastudy-e1ba2.web.app logo and branding to current page
 */
function addHeader(doc: jsPDF, logoBase64: string | null, margin: number, pageWidth: number): number {
  const headerY = margin;
  
  // Add logo image
  if (logoBase64) {
    try {
      doc.addImage(logoBase64, 'PNG', margin, headerY, 10, 10);
    } catch {
      // Fallback if logo fails
    }
  }
  
  // Add "Generated by metastudy-e1ba2.web.app" text next to logo
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by metastudy-e1ba2.web.app', margin + 12, headerY + 6);
  
  // Draw header separator line
  doc.setDrawColor(59, 130, 246);
  doc.setLineWidth(0.5);
  doc.line(margin, headerY + 12, pageWidth - margin, headerY + 12);
  
  return headerY + 18; // Return Y position for content to start
}

/**
 * Cross-platform PDF download that works on Windows, macOS Preview, iOS, etc.
 * Uses Blob + object URL instead of jsPDF's built-in save() for better compat.
 */
function savePDFCrossPlatform(doc: jsPDF, filename: string): void {
  const finalFilename = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;

  try {
    // Get the PDF as a Blob with the correct MIME type
    const blob = doc.output('blob');
    // Re-wrap with explicit type so every browser/OS recognises it
    const pdfBlob = new Blob([blob], { type: 'application/pdf' });
    const url = URL.createObjectURL(pdfBlob);

    const link = document.createElement('a');
    link.href = url;
    link.download = finalFilename;
    link.style.display = 'none';
    document.body.appendChild(link);
    link.click();

    // Cleanup after a short delay so the download can start
    setTimeout(() => {
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    }, 250);
  } catch {
    // Ultimate fallback - let jsPDF try its own save()
    doc.save(finalFilename);
  }
}

/**
 * Generate and auto-download a PDF with text content using jsPDF
 */
export const downloadPDF = async (content: string, options: PDFOptions): Promise<void> => {
  const { filename, margin = 20, pageSize = 'letter' } = options;
  
  if (!content || content.trim().length === 0) {
    throw new Error('No content to generate PDF');
  }
  
  // Load logo
  let logoBase64: string | null = null;
  try {
    logoBase64 = await loadImageBase64(logoUrl);
  } catch {
    // Continue without logo if it fails
  }
  
  // Create PDF document
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: pageSize,
    compress: true,
  });

  // Set PDF metadata for better OS compatibility
  doc.setProperties({
    title: filename.replace(/\.pdf$/i, ''),
    creator: 'metastudy-e1ba2.web.app',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const usableWidth = pageWidth - (margin * 2);
  const bottomLimit = pageHeight - margin - 10;
  
  // Add header on first page
  let y = addHeader(doc, logoBase64, margin, pageWidth);
  
  // Strip any residual HTML tags and decode entities
  const cleanText = content
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>/gi, '\n\n')
    .replace(/<\/div>/gi, '\n')
    .replace(/<\/h[1-6]>/gi, '\n\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  
  // Sanitize for PDF font compatibility (macOS Preview is strict about this)
  const textToRender = sanitizeForPDF(cleanText.length > 0 ? cleanText : content.trim());
  
  // Set consistent body text style
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 30, 30);
  
  // Split text into lines that fit the page width
  const lines = doc.splitTextToSize(textToRender, usableWidth);
  const lineHeight = 5;
  
  for (let i = 0; i < lines.length; i++) {
    // Check if we need a new page
    if (y + lineHeight > bottomLimit) {
      doc.addPage();
      y = addHeader(doc, logoBase64, margin, pageWidth);
      // Re-set body text style after header
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(11);
      doc.setTextColor(30, 30, 30);
    }
    
    const lineText = String(lines[i] || '');
    doc.text(lineText, margin, y);
    y += lineHeight;
  }
  
  // Download via cross-platform method
  savePDFCrossPlatform(doc, filename);
};

/**
 * Generate plain text content for a summary PDF
 */
export const generateSummaryPDFHTML = (
  title: string,
  content: string,
  createdAt?: string
): string => {
  const date = createdAt ? new Date(createdAt).toLocaleDateString() : new Date().toLocaleDateString();

  return `${title}\nSummary, Generated on ${date}\n\n${content}`;
};

/**
 * Generate plain text content for a lesson PDF
 */
export const generateLessonPDFHTML = (lesson: {
  title: string;
  subject?: string;
  sections?: Array<{
    title: string;
    content: string;
    keyPoints?: string[];
  }>;
}): string => {
  const sectionsText = (lesson.sections || []).map((section, idx) => {
    let text = `${idx + 1}. ${section.title}\n\n${section.content}`;
    if (section.keyPoints && section.keyPoints.length > 0) {
      text += `\n\nKey Points:\n${section.keyPoints.map(kp => `- ${kp}`).join('\n')}`;
    }
    return text;
  }).join('\n\n');

  let header = lesson.title;
  if (lesson.subject) header += `\nSubject: ${lesson.subject}`;
  
  return `${header}\n\n${sectionsText || 'No content available.'}`;
};

/**
 * Generate plain text content for a resume PDF
 */
export const generateResumePDFHTML = (
  data: {
    fullName?: string;
    email?: string;
    phone?: string;
    location?: string;
    linkedin?: string;
    website?: string;
  },
  sections: Array<{
    id: string;
    title: string;
    content: string;
  }>,
  _fontFamily: string = 'Georgia'
): string => {
  const contactParts = [
    data.email,
    data.phone,
    data.location,
    data.linkedin,
    data.website
  ].filter(Boolean);

  const sectionsText = sections.map(section => 
    `${section.title.toUpperCase()}\n${section.content}`
  ).join('\n\n');

  let header = data.fullName || 'Your Name';
  if (contactParts.length > 0) header += `\n${contactParts.join(' | ')}`;
  
  return `${header}\n\n${sectionsText || 'No content available.'}`;
};
